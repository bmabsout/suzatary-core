//! The choices a deployment begins from, as the Markdown `AGENT.md` holds between its options
//! markers: a reading of `init`'s own argument tree, its value enums and the steps
//! [`Onboarding::steps`](super::Onboarding::steps) prints, never a second list of them. `suzatary init --options` prints
//! it, and a guard holds the committed file to it, so the guide and the verb cannot offer
//! different choices.

use std::fmt::Write as _;

use clap::{CommandFactory as _, ValueEnum};
use suzatary_core::cast::CAST;
use suzatary_core::plugin::World;
use suzatary_core::settings::Preset;

use super::{Brain, FirstAccount, Flags, Provider, Reach};

/// The line before the generated text in `AGENT.md`.
pub const BEGIN: &str =
    "<!-- options: generated by `suzatary init --options`; edit the code, never this text -->";

/// The line after it.
pub const END: &str = "<!-- end of options -->";

/// How the steps are spelled: through the user repository's script, as the guide runs them.
const SCRIPT: &str = "./suzatary";

/// The flags `init` takes that choose nothing about the deployment.
const NOT_CHOICES: [&str; 3] = ["help", "force", "options"];

/// Each world, in the order the guide lists them; a new world is a new arm in [`about`], which
/// fails to compile until it has one.
const WORLDS: [World; 2] = [World::Source, World::Actor];

/// The options, from [`BEGIN`] to [`END`] inclusive, ending with a newline.
#[must_use]
pub fn markdown() -> String {
    let reach = Reach::Script(SCRIPT.to_owned());
    let mut out = format!("{BEGIN}\n\n");
    flags(&mut out);
    mail(&mut out, &reach);
    models(&mut out, &reach);
    connectors(&mut out);
    out.push_str(END);
    out.push('\n');
    out
}

/// Every flag `init` asks, with its own help.
fn flags(out: &mut String) {
    out.push_str("### Who, where, and who may come in\n\n");
    out.push_str("`init` asks for any of these it is not given, at a terminal.\n\n");
    out.push_str("| Flag | What it sets |\n|---|---|\n");
    let command = Flags::command();
    for arg in command.get_arguments() {
        let (Some(long), Some(help)) = (arg.get_long(), arg.get_help()) else {
            continue;
        };
        if NOT_CHOICES.contains(&long) {
            continue;
        }
        let _ = writeln!(out, "| `--{long}` | {} |", one_line(&help.to_string()));
    }
    out.push('\n');
}

/// Each provider a first account may be with, and the sign-in it leaves.
fn mail(out: &mut String, reach: &Reach) {
    out.push_str("### Mail\n\n");
    out.push_str(
        "One account at `init` (`--email` and `--mail-provider`); more are added to \
         `[[mail.accounts]]` later. Each provider leaves a sign-in only the person can do:\n\n",
    );
    for provider in Provider::value_variants() {
        let first = FirstAccount {
            provider: *provider,
            email: CAST.owner.email.to_owned(),
        };
        choice(out, provider);
        block(out, &first.steps(reach));
    }
}

/// The model `init` sets, the secret each needs, and the backends added after.
fn models(out: &mut String, reach: &Reach) {
    out.push_str("### Model\n\n");
    out.push_str(
        "`--model`; every job answers with it until a tapped card orders others. Its secret \
         is set at a terminal as below, or, once the app runs, from the **Connect a model** card \
         the box files in the Inbox whenever no job's model answers.\n\n",
    );
    for brain in Brain::value_variants() {
        choice(out, brain);
        block(out, &brain.steps(reach));
    }
    out.push_str(
        "Other backends are declared after `init`, by a card the secretary files when asked and \
         you tap. The box then files a \
         card in the Inbox asking for each one's key, under its own name:\n\n| Backend | \
         Secret |\n|---|---|\n",
    );
    for preset in Preset::ALL {
        let _ = writeln!(out, "| `{}/` | `{}` |", preset.backend(), preset.key_name());
    }
    out.push('\n');
}

/// The worlds a connector (a calendar, any other service) is written against.
fn connectors(out: &mut String) {
    out.push_str("### Calendars and other connectors\n\n");
    out.push_str(
        "A connector is a plugin, a WebAssembly component of one world, declared by a \
         `[[plugins]]` table that names every origin and credential it may use. The app ships \
         the calendar (`ics`, a `source`, one secret iCal link per calendar, each a `url` \
         credential named `PLUGIN_ICS_<LABEL>`). The worlds:\n\n",
    );
    for world in WORLDS {
        let imports = world.imports().join("`, `");
        let _ = writeln!(out, "- `{world}`: {} Imports `{imports}`.", about(world));
    }
    out.push('\n');
}

/// What a world's plugins do.
const fn about(world: World) -> &'static str {
    match world {
        World::Source => {
            "reads a service from a cursor into its own cache store; the only world that fetches."
        }
        World::Actor => {
            "reads a store and proposes cards the owner taps; it fetches nothing and performs \
             nothing."
        }
    }
}

/// One value of a flag's enum, as a list item: its spelling and its help.
fn choice(out: &mut String, value: &impl ValueEnum) {
    if let Some(value) = value.to_possible_value() {
        let help = value.get_help().map(|help| one_line(&help.to_string()));
        let _ = writeln!(
            out,
            "- `{}`: {}",
            value.get_name(),
            help.unwrap_or_default()
        );
    }
}

/// Steps as a console block indented under their list item; nothing for none.
fn block(out: &mut String, steps: &[super::Step]) {
    if steps.is_empty() {
        out.push('\n');
        return;
    }
    out.push_str("\n  ```console\n");
    for step in steps {
        let _ = writeln!(out, "  $ {}   # {}", step.command, step.why);
    }
    out.push_str("  ```\n\n");
}

/// Help text on one line, for a table cell or a list item.
fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_provider_and_model_is_offered_with_each_step_it_prints() {
        let text = markdown();
        let reach = Reach::Script(SCRIPT.to_owned());
        for provider in Provider::value_variants() {
            let name = provider.to_possible_value().expect("shown");
            assert!(text.contains(&format!("- `{}`:", name.get_name())));
            let first = FirstAccount {
                provider: *provider,
                email: CAST.owner.email.to_owned(),
            };
            for step in first.steps(&reach) {
                assert!(text.contains(&step.command), "{}", step.command);
            }
        }
        for brain in Brain::value_variants() {
            for step in brain.steps(&reach) {
                assert!(text.contains(&step.command), "{}", step.command);
            }
        }
        for preset in Preset::ALL {
            assert!(text.contains(preset.key_name()));
        }
    }

    #[test]
    fn every_flag_that_chooses_is_listed_and_none_that_does_not() {
        let text = markdown();
        for arg in Flags::command().get_arguments() {
            let Some(long) = arg.get_long() else { continue };
            let row = format!("| `--{long}` |");
            assert_eq!(text.contains(&row), !NOT_CHOICES.contains(&long), "{long}");
        }
    }

    #[test]
    fn the_text_is_bracketed_by_its_markers() {
        let text = markdown();
        assert!(text.starts_with(BEGIN));
        assert!(text.ends_with(&format!("{END}\n")));
        assert_eq!(text.matches(BEGIN).count(), 1);
    }
}
